"""MuJoCo rollout of a two-finger parallel gripper squeezing then lifting a
box of randomized mass and friction. No real robot or real sensor data
anywhere in this repository; every number below is generated by MuJoCo's
rigid-body contact solver, not hand-derived analytically.
"""

import numpy as np
import mujoco

import config


def make_model_data():
    model = mujoco.MjModel.from_xml_path(config.MODEL_XML)
    data = mujoco.MjData(model)
    return model, data


def run_trial(model, data, mass, mu, grip_policy, rng, solve_time_log=None):
    """grip_policy(tick, box_z_vision, n_meas, palm_z) -> grip_force command (N, per finger pair total).

    Returns dict with success, final box_z, final palm_z, estimate history (if the
    policy exposes one via grip_policy.last_estimate).
    """
    mujoco.mj_resetData(model, data)
    box_body = model.body("box").id
    box_geom = model.geom("box_geom").id
    palm_joint_adr = model.joint("palm_z").qposadr[0]
    left_force_adr = model.sensor("left_force").adr[0]
    right_force_adr = model.sensor("right_force").adr[0]

    model.body_mass[box_body] = mass
    model.geom_friction[box_geom] = [mu, 0.01, 0.0001]

    dt = model.opt.timestep
    n_ticks = int(round(config.TRIAL_DURATION_S * config.CONTROL_HZ))
    grip_cmd = 0.0
    estimate_history = []
    min_box_z_margin = np.inf

    for tick in range(n_ticks):
        t = tick / config.CONTROL_HZ

        grip_frac = min(1.0, t / config.SQUEEZE_RAMP_S)
        if t > config.SQUEEZE_RAMP_S + config.LIFT_START_S:
            lift_t = min(1.0, (t - config.SQUEEZE_RAMP_S - config.LIFT_START_S) /
                         (config.TRIAL_DURATION_S - config.SQUEEZE_RAMP_S - config.LIFT_START_S))
        else:
            lift_t = 0.0

        box_z_true = data.xpos[box_body][2]
        palm_z_true = data.qpos[palm_joint_adr]
        box_z_vision = box_z_true + rng.normal(0.0, config.VISION_NOISE_SIGMA)

        left_f = abs(data.sensordata[left_force_adr])
        right_f = abs(data.sensordata[right_force_adr])
        n_meas_true = 0.5 * (left_f + right_f)
        n_meas = n_meas_true + rng.normal(0.0, config.FORCE_NOISE_SIGMA)

        import time as _time
        t0 = _time.perf_counter()
        grip_cmd = grip_policy(tick, box_z_vision, n_meas, palm_z_true)
        if solve_time_log is not None:
            solve_time_log.append(_time.perf_counter() - t0)
        grip_cmd = float(np.clip(grip_cmd, config.GRIP_CTRL_MIN, config.GRIP_CTRL_MAX))

        data.ctrl[0] = grip_cmd * grip_frac
        data.ctrl[1] = -grip_cmd * grip_frac
        data.ctrl[2] = config.LIFT_HEIGHT * lift_t

        for _ in range(config.CONTROL_SUBSTEPS):
            mujoco.mj_step(model, data)

        min_box_z_margin = min(min_box_z_margin, box_z_true - palm_z_true)

        if getattr(grip_policy, "last_estimate", None) is not None:
            estimate_history.append(tuple(grip_policy.last_estimate))

    final_box_z = data.xpos[box_body][2]
    final_palm_z = data.qpos[palm_joint_adr]
    held = abs(final_box_z - final_palm_z) < config.HOLD_TOL
    reached_target = final_palm_z > (config.LIFT_HEIGHT - 0.01)
    success = bool(held and reached_target)

    return {
        "success": success,
        "final_box_z": float(final_box_z),
        "final_palm_z": float(final_palm_z),
        "estimate_history": estimate_history,
        "true_mass": mass,
        "true_mu": mu,
    }
